package dev.panasko.photoliz.ui

import android.graphics.Canvas
import android.graphics.Paint
import kotlin.math.floor
import kotlin.math.max

/** 12x12 pixel-art icons, drawn as crisp squares (old camera LCD look). Same art is used on iOS. */
class PixelIcon(rows: Array<String>) {
    val size = rows.size
    private val bits = BooleanArray(size * size) { i -> rows[i / size].getOrElse(i % size) { '.' } == '#' }

    fun draw(canvas: Canvas, cx: Float, cy: Float, sizePx: Float, paint: Paint) {
        // Integer pixel size keeps edges crisp.
        val px = max(1f, floor(sizePx / size))
        val total = px * size
        val left = floor(cx - total / 2f)
        val top = floor(cy - total / 2f)
        for (y in 0 until size) {
            var x = 0
            while (x < size) {
                if (!bits[y * size + x]) { x++; continue }
                var run = x
                while (run < size && bits[y * size + run]) run++
                canvas.drawRect(left + x * px, top + y * px, left + run * px, top + (y + 1) * px, paint)
                x = run
            }
        }
    }
}

